INSERT INTO industry_tags (code, name, level, parent_id, category)
SELECT d.code, d.name, 2, p.id, p.category
FROM data d
JOIN industry_tags p ON p.code = d.parent_code
ON CONFLICT (code) DO UPDATE SET
    name = EXCLUDED.name,
    level = EXCLUDED.level,
    parent_id = EXCLUDED.parent_id,
    category = EXCLUDED.category;

